#!/usr/bin/env bash
# Docker-free test of the D16c core settings library
# (core/docker/vault-settings-lib.sh) and of the boot hook
# 15-vault-settings.envsh where it needs no image:
#   - vs_parse accepts exactly what vault-api writes (api/vault_api/
#     core_settings.py render_file) and rejects the WHOLE file for: no or a
#     wrong header, no/bad GENERATION, an unknown key, a duplicate key, a
#     line without '=', a CR, a non-printable value, too many lines;
#   - vs_resolve: a non-blank env value wins, else the file, else the
#     default; a blank or whitespace-only env value counts as not set;
#   - vs_capture_env records the env once (a second call keeps the first);
#   - vs_write_status writes valid JSON with every key, and vs_shown keeps
#     quotes, backslashes and control characters out of it;
#   - 15- sourced under `set -e` with no settings file: defaults exported,
#     the env pin kept, the generation include says 0, the deprecated
#     VAULT_UPSTREAM_RATE_WINDOW env pin warns; with a malformed file: boots
#     on env + defaults and reports "rejected".
# The render with a VALID file (20-envsubst, nginx -t, the reload) needs the
# pinned image: .github/scripts/verify-core-nginx.sh and
# deploy/tests/verify-stack.sh run it.
#
#     bash core/tests/test-settings-lib.sh
# The sh -c snippets expand their variables in the child shell on purpose.
# shellcheck disable=SC2016
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
docker_dir="$(cd "$script_dir/../docker" && pwd)"
LIB="$docker_dir/vault-settings-lib.sh"
HOOK15="$docker_dir/15-vault-settings.envsh"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT INT TERM

pass=0
fail=0
ok()  { echo "ok:   $1"; pass=$((pass + 1)); }
bad() { echo "FAIL: $1" >&2; fail=$((fail + 1)); }

HEADER="# generated by vault-api -- do not edit"

# --- vs_parse ----------------------------------------------------------------
good_file=$(printf '%s\n' "$HEADER" GENERATION=42 VAULT_UPSTREAM_RATE=800k VAULT_UPSTREAM_RATE_WINDOW=03:00-07:00 \
    "VAULT_UPSTREAM_POOL_HOSTS=cache1-fra2.steamcontent.com dist-fra1.discovery.steamserver.net" VAULT_RESOLVER=1.1.1.1)
out=$(env -i PATH="$PATH" sh -c '. "$1"; vs_parse "$2" && echo "gen=$VS_GEN rate=$VS_F_VAULT_UPSTREAM_RATE has=$VS_HAS_VAULT_UPSTREAM_RATE pool=$VS_F_VAULT_UPSTREAM_POOL_HOSTS edge_has=[$VS_HAS_VAULT_UPSTREAM_EDGE]"' sh "$LIB" "$good_file" 2>&1) || true
if [ "$out" = "gen=42 rate=800k has=1 pool=cache1-fra2.steamcontent.com dist-fra1.discovery.steamserver.net edge_has=[]" ]; then
    ok "parse: the vault-api file shape"
else
    bad "parse: the vault-api file shape -> $out"
fi

# reject <label> <expected VS_ERR substring> <file content>
reject() {
    local out rc=0
    out=$(env -i PATH="$PATH" sh -c '. "$1"; if vs_parse "$2"; then echo "ACCEPTED gen=$VS_GEN"; exit 0; fi; echo "$VS_ERR"; exit 3' sh "$LIB" "$3" 2>&1) || rc=$?
    if [ "$rc" = 3 ] && grep -qF -- "$2" <<<"$out"; then
        ok "parse rejects: $1"
    else
        bad "parse rejects: $1 (rc=$rc): $out"
    fi
}
reject "no header"            "line 1 is not the vault-api header" "$(printf '%s\n' GENERATION=1 VAULT_UPSTREAM_RATE=1m)"
reject "a different header"   "line 1 is not the vault-api header" "$(printf '%s\n' '# generated by someone' GENERATION=1)"
reject "no GENERATION"        "line 2 is not GENERATION" "$(printf '%s\n' "$HEADER" VAULT_UPSTREAM_RATE=1m)"
reject "GENERATION 0"         "GENERATION is not a positive" "$(printf '%s\n' "$HEADER" GENERATION=0)"
reject "GENERATION 007"       "GENERATION is not a positive" "$(printf '%s\n' "$HEADER" GENERATION=007)"
reject "GENERATION x"         "GENERATION is not a positive" "$(printf '%s\n' "$HEADER" GENERATION=1x)"
reject "GENERATION 16 digits" "more than 15 digits" "$(printf '%s\n' "$HEADER" GENERATION=1234567890123456)"
reject "header only"          "no GENERATION line" "$HEADER"
reject "unknown key"          "key 'VAULT_API_KEY' is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 VAULT_API_KEY=secret)"
reject "env-only core key"    "key 'VAULT_TLS_PASSTHROUGH' is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 VAULT_TLS_PASSTHROUGH=0)"
reject "lowercase key"        "is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 vault_upstream_rate=1m)"
reject "PATH injection"       "key 'PATH' is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 PATH=/tmp)"
# Review D16c B2: a "key" made of several allowlisted names, or with other
# characters, never matches the allowlist (exact literal match only).
reject "multi-key line"       "is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 'VAULT_UPSTREAM_RATE VAULT_UPSTREAM_RATE_WINDOW=800k')"
reject "key with a \$"        "is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 'VAULT_UPSTREAM_RATE$(id)=1m')"
reject "key with a ;"         "is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 'VAULT_UPSTREAM_RATE;x=1m')"
reject "key with spaces"      "is not a core setting" "$(printf '%s\n' "$HEADER" GENERATION=1 ' VAULT_UPSTREAM_RATE=1m')"
reject "duplicate key"        "VAULT_UPSTREAM_RATE is listed twice" "$(printf '%s\n' "$HEADER" GENERATION=1 VAULT_UPSTREAM_RATE=1m VAULT_UPSTREAM_RATE=2m)"
reject "a comment line"       "is not KEY=VALUE" "$(printf '%s\n' "$HEADER" GENERATION=1 '# note')"
reject "an empty line"        "is not KEY=VALUE" "$(printf '%s\n' "$HEADER" GENERATION=1 '' VAULT_UPSTREAM_RATE=1m)"
reject "CRLF"                 "carriage return" "$(printf '%s\r\n%s\r\n' "$HEADER" GENERATION=1)"
reject "control character"    "outside printable ASCII" "$(printf '%s\n%s\n%s\001\n' "$HEADER" GENERATION=1 VAULT_RESOLVER=1.1.1.1)"
reject "non-ASCII value"      "outside printable ASCII" "$(printf '%s\n%s\n%s\n' "$HEADER" GENERATION=1 "VAULT_UPSTREAM_RATE_WINDOW=03:00$(printf '\xc2\xa0')-07:00")"
many=$(printf '%s\n' "$HEADER" GENERATION=1; for i in $(seq 1 70); do echo "VAULT_UPSTREAM_RATE=$i"; done)
reject "too many lines"       "more than 64 lines" "$many"
# A command substitution inside a value is data, never run.
out=$(env -i PATH="$PATH" sh -c '. "$1"; vs_parse "$2" && printf "%s" "$VS_F_VAULT_RESOLVER"' sh "$LIB" "$(printf '%s\n' "$HEADER" GENERATION=3 'VAULT_RESOLVER=$(touch '"$work"'/pwned)')" 2>&1) || true
if [ ! -e "$work/pwned" ] && [ "$out" = "\$(touch $work/pwned)" ]; then
    ok "parse: a \$(...) value is kept as text, never executed"
else
    bad "parse: a \$(...) value -> '$out', pwned file: $([ -e "$work/pwned" ] && echo yes || echo no)"
fi

# --- vs_resolve / vs_capture_env -----------------------------------------------
resolve_out=$(env -i PATH="$PATH" VAULT_UPSTREAM_RATE=4m VAULT_UPSTREAM_EDGE='   ' VAULT_RESOLVER= sh -c '
    . "$1"; vs_capture_env
    VAULT_UPSTREAM_RATE=changed; vs_capture_env
    vs_parse "$2"; vs_resolve yes
    for k in VAULT_UPSTREAM_RATE VAULT_UPSTREAM_RATE_WINDOW VAULT_UPSTREAM_EDGE VAULT_UPSTREAM_POOL_HOSTS VAULT_RESOLVER VAULT_UPSTREAM_MAX_CONNS; do
        eval "echo \$k=\$VS_V_$k/\$VS_S_$k"
    done
    vs_resolve no
    echo "nofile:VAULT_UPSTREAM_POOL_HOSTS=$VS_V_VAULT_UPSTREAM_POOL_HOSTS/$VS_S_VAULT_UPSTREAM_POOL_HOSTS"' sh "$LIB" \
    "$(printf '%s\n' "$HEADER" GENERATION=5 VAULT_UPSTREAM_RATE=800k VAULT_UPSTREAM_EDGE=off "VAULT_UPSTREAM_POOL_HOSTS=cache1-fra2.steamcontent.com" VAULT_UPSTREAM_RATE_WINDOW=off)" 2>&1) || true
expect_resolve="VAULT_UPSTREAM_RATE=4m/env
VAULT_UPSTREAM_RATE_WINDOW=off/file
VAULT_UPSTREAM_EDGE=off/file
VAULT_UPSTREAM_POOL_HOSTS=cache1-fra2.steamcontent.com/file
VAULT_RESOLVER=1.1.1.1/default
VAULT_UPSTREAM_MAX_CONNS=16/default
nofile:VAULT_UPSTREAM_POOL_HOSTS=off/default"
if [ "$resolve_out" = "$expect_resolve" ]; then
    ok "resolve: env > file > default; blank and whitespace env = not set; env captured once"
else
    bad "resolve: got
$resolve_out"
fi

# vs_is_key's literal list equals VS_KEYS exactly (both directions).
iskey=$(env -i PATH="$PATH" sh -c '. "$1"; for k in $VS_KEYS; do vs_is_key "$k" || echo "missing $k"; done
    for k in VAULT_API_KEY VAULT_UPSTREAM VAULT_UPSTREAM_RATEX "VAULT_UPSTREAM_RATE VAULT_RESOLVER" ""; do vs_is_key "$k" && echo "extra [$k]"; done; true' sh "$LIB")
if [ -z "$iskey" ]; then ok "vs_is_key accepts exactly the VS_KEYS names"; else bad "vs_is_key: $iskey"; fi

# Every allowlisted key has a default (the hooks never see a blank value).
missing=$(env -i PATH="$PATH" sh -c '. "$1"; for k in $VS_KEYS; do vs_default "$k" >/dev/null || echo "$k"; done' sh "$LIB")
if [ -z "$missing" ]; then ok "every key has a default"; else bad "keys without a default: $missing"; fi

# The allowlist equals vault-api's FILE_KEYS (api/vault_api/core_settings.py).
api_keys=$(awk '/^FILE_KEYS = \(/ { f = 1; next } f && /^\)/ { exit } f { gsub(/[ ",]/, ""); if ($0 != "") print }' \
    "$script_dir/../../api/vault_api/core_settings.py" | tr '\n' ' ' | sed 's/ $//')
lib_keys=$(env -i PATH="$PATH" sh -c '. "$1"; echo "$VS_KEYS"' sh "$LIB")
if [ -n "$api_keys" ] && [ "$api_keys" = "$lib_keys" ]; then
    ok "the key allowlist equals vault-api's FILE_KEYS, in order"
else
    bad "allowlist drift: lib '$lib_keys' vs api '$api_keys'"
fi

# --- vs_write_status / vs_shown --------------------------------------------------
mkdir -p "$work/logs"
printf 'VAULT_UPSTREAM_RATE=800k\tfile\nVAULT_RESOLVER=[2606:4700::1111]:53\tenv\nVAULT_UPSTREAM_EDGE=off\tdefault\n' > "$work/effective"
env -i PATH="$PATH" VS_STATUS_FILE="$work/logs/settings-applied.json" sh -c '. "$1"; vs_write_status rejected 9 8 "$2" "$3"' sh "$LIB" \
    "$(printf 'bad "quote" \\ back\nslash\tand tab')" "$work/effective" || bad "status: vs_write_status failed"
if python3 - "$work/logs/settings-applied.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
assert d["component"] == "vault-core" and d["state"] == "rejected", d
assert d["generation"] == 9 and d["applied_generation"] == 8, d
assert '"' not in d["reason"] and "\\" not in d["reason"] and "\n" not in d["reason"] and "\t" not in d["reason"], d["reason"]
assert d["keys"]["VAULT_UPSTREAM_RATE"] == {"value": "800k", "source": "file"}, d["keys"]
assert d["keys"]["VAULT_RESOLVER"] == {"value": "[2606:4700::1111]:53", "source": "env"}, d["keys"]
assert d["keys"]["VAULT_UPSTREAM_EDGE"] == {"value": "off", "source": "default"}, d["keys"]
PY
then
    ok "status: valid JSON, quotes/backslashes/control characters cannot reach it, IPv6 brackets kept"
else
    bad "status: $(cat "$work/logs/settings-applied.json")"
fi
if [ "$(stat -c %a "$work/logs/settings-applied.json")" = 644 ] && [ -z "$(find "$work/logs" -name '.settings-applied.*')" ]; then
    ok "status: 0644, no temp file left"
else
    bad "status: mode $(stat -c %a "$work/logs/settings-applied.json") or a temp file left"
fi

# --- 15-vault-settings.envsh (sourced, as the stock entrypoint does, under set -e) ---
# boot15 <settings file path> <env assignments...>: sources the hook like the
# stock entrypoint (set -e, fd 3), then prints the exported values.
boot15() {
    local file="$1"
    shift
    mkdir -p "$work/etc"
    rm -f "$work/etc"/*
    env -i PATH="$PATH" VS_LIB="$LIB" VS_SETTINGS_FILE="$file" VS_CONF_DIR="$work/etc" "$@" sh -c '
        set -e
        exec 3>&1
        . "$1"
        echo "STATE=$VS_BOOT_STATE GEN=$VS_BOOT_GEN SEEN=$VS_BOOT_SEEN"
        echo "REASON=$VS_BOOT_REASON"
        for k in VAULT_UPSTREAM_RATE VAULT_UPSTREAM_RATE_WINDOW VAULT_UPSTREAM_EDGE VAULT_RESOLVER VAULT_TLS_MAX_CONNS; do
            eval "echo EXPORT \$k=\$$k"
        done
        sh -c "echo CHILD VAULT_UPSTREAM_EDGE=\$VAULT_UPSTREAM_EDGE VS_ENV_VAULT_UPSTREAM_RATE=\$VS_ENV_VAULT_UPSTREAM_RATE"
    ' sh "$HOOK15" 2>&1
}
out=$(boot15 "$work/absent.env" VAULT_UPSTREAM_RATE=2m VAULT_UPSTREAM_EDGE= ) || true
for want in "STATE=none GEN=0 SEEN=0" "EXPORT VAULT_UPSTREAM_RATE=2m" "EXPORT VAULT_UPSTREAM_RATE_WINDOW=03:00-07:00" \
            "EXPORT VAULT_UPSTREAM_EDGE=dist-fra1.discovery.steamserver.net" "EXPORT VAULT_RESOLVER=1.1.1.1" \
            "EXPORT VAULT_TLS_MAX_CONNS=256" \
            "CHILD VAULT_UPSTREAM_EDGE=dist-fra1.discovery.steamserver.net VS_ENV_VAULT_UPSTREAM_RATE=2m"; do
    if grep -qxF -- "$want" <<<"$out"; then ok "15- without a file: $want"; else bad "15- without a file: no '$want' in:
$out"; fi
done
if grep -qxF 'add_header X-Vault-Settings-Generation "0" always;' "$work/etc/vault-settings-generation.conf" \
   && grep -qxF "$(printf 'VAULT_UPSTREAM_RATE=2m\tenv')" "$work/etc/vault-settings.effective" \
   && grep -qxF "$(printf 'VAULT_RESOLVER=1.1.1.1\tdefault')" "$work/etc/vault-settings.effective"; then
    ok "15- without a file: generation include 0 and the effective file with sources"
else
    bad "15- without a file: $(cat "$work/etc/vault-settings-generation.conf" "$work/etc/vault-settings.effective" 2>&1)"
fi
if grep -qx '15-vault-settings.envsh: VAULT_UPSTREAM_RATE=2m (env)' <<<"$out"; then
    ok "15- logs each key with its source"
else
    bad "15- log line missing: $out"
fi

out=$(boot15 "$work/absent.env" VAULT_UPSTREAM_RATE_WINDOW=22:00-06:00) || true
if grep -q 'WARNING: VAULT_UPSTREAM_RATE_WINDOW=.22:00-06:00. is set in the environment. It is deprecated' <<<"$out" \
   && grep -qxF 'EXPORT VAULT_UPSTREAM_RATE_WINDOW=22:00-06:00' <<<"$out"; then
    ok "15- warns about the deprecated VAULT_UPSTREAM_RATE_WINDOW env pin and still honours it"
else
    bad "15- deprecated window: $out"
fi

printf '%s\n' "$HEADER" GENERATION=4 VAULT_API_KEY=x > "$work/bad.env"
out=$(boot15 "$work/bad.env" VAULT_UPSTREAM_RATE=) || true
# Review D16c S1: the rejected file's generation is reported as seen (so
# vault-api's "pending" ends), the live generation stays 0.
if grep -qxF 'STATE=rejected GEN=0 SEEN=4' <<<"$out"; then
    if grep -q "REASON=settings file rejected: line 3: key 'VAULT_API_KEY' is not a core setting" <<<"$out" \
       && grep -qxF 'EXPORT VAULT_UPSTREAM_RATE=off' <<<"$out"; then
        ok "15- with a malformed file: boots on env + defaults, reports rejected with the reason"
    else
        bad "15- with a malformed file: $out"
    fi
else
    bad "15- with a malformed file: $out"
fi
if grep -qxF 'add_header X-Vault-Settings-Generation "0" always;' "$work/etc/vault-settings-generation.conf"; then
    ok "15- with a malformed file: generation include stays 0"
else
    bad "15- with a malformed file: generation include $(cat "$work/etc/vault-settings-generation.conf" 2>&1)"
fi

mkfifo "$work/fifo.env"
out=$(boot15 "$work/fifo.env") || true
if grep -qxF 'STATE=rejected GEN=0 SEEN=0' <<<"$out" && grep -q 'not a readable regular file' <<<"$out"; then
    ok "15- with a FIFO as the settings file: rejected, no hang"
else
    bad "15- with a FIFO: $out"
fi

echo "test-settings-lib: $pass passed, $fail failed"
[ "$fail" = 0 ]
