#!/usr/bin/env bash
# Docker-free, deterministic test of the settings watcher's apply path
# (core/docker/47-vault-settings-watch.sh, apply_file), with every external
# piece stubbed (review D16c S2/S5):
#   - the hooks (20-envsubst .. 45-) are stubs that render marker files;
#   - nginx (-t) is a PATH stub that passes;
#   - the nginx master is a real process named "nginx: master process" that
#     counts the SIGHUPs it gets;
#   - wget is a PATH stub that serves a FIXED X-Vault-Settings-Apply id.
# Cases:
#   1. rollback: /health never shows the new apply id -> timeout ->
#      restore_backup -> second reload -> status "rejected: reload failed",
#      the live files byte-identical to the backup, two SIGHUPs;
#   2. success: /health shows the new id -> status "applied", the staged
#      files are live, one SIGHUP;
#   3. transient failure (no master): apply_file returns 2 (the loop retries
#      the same content), the live files untouched, no SIGHUP;
#   4. a content failure (render refused) returns 0 (no retry);
#   6. the watch loop: a transient failure is retried on the next ticks (same
#      content, no change needed), logged and written to the status file
#      ONCE for the whole streak, and applied as soon as the master is back.
#
#     bash core/tests/test-settings-watch.sh
# The bash -c snippets expand their variables in the child shell on purpose.
# shellcheck disable=SC2016
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
docker_dir="$(cd "$script_dir/../docker" && pwd)"

work="$(mktemp -d)"
master_pid=""
cleanup() {
    [ -z "$master_pid" ] || kill "$master_pid" 2>/dev/null || true
    rm -rf "$work"
}
trap cleanup EXIT INT TERM

pass=0
fail=0
ok()  { echo "ok:   $1"; pass=$((pass + 1)); }
bad() { echo "FAIL: $1" >&2; fail=$((fail + 1)); }

HEADER="# generated by vault-api -- do not edit"
RENDERED="nginx.conf vault-upstream-rate.conf vault-upstream-pool.conf vault-upstream-cap.conf vault-settings-generation.conf vault-settings.effective"

# --- stubs ---------------------------------------------------------------------
mkdir -p "$work/hooks" "$work/bin" "$work/etc" "$work/logs"
cat > "$work/hooks/20-envsubst-on-templates.sh" <<'EOF'
#!/bin/sh
printf 'log_format vault_event x;\n# staged %s\n' "$VAULT_UPSTREAM_RATE" > "$NGINX_ENVSUBST_OUTPUT_DIR/nginx.conf"
EOF
for h in 25-vault-eventlog.sh 26-vault-tls-passthrough.sh 40-vault-preflight.sh; do
    printf '#!/bin/sh\nexit 0\n' > "$work/hooks/$h"
done
cat > "$work/hooks/27-vault-upstream-rate.sh" <<'EOF'
#!/bin/sh
[ "$VAULT_UPSTREAM_RATE" != refuse ] || { echo "27-vault-upstream-rate.sh: FATAL: stub refusal"; exit 1; }
printf 'staged rate %s\n' "$VAULT_UPSTREAM_RATE" > "$1"
EOF
cat > "$work/hooks/28-vault-upstream-pool.sh" <<'EOF'
#!/bin/sh
printf 'staged pool\n' > "$1"
printf 'staged cap\n' > "$(dirname "$1")/vault-upstream-cap.conf"
EOF
cp "$docker_dir/31-vault-debug-throughput.sh" "$docker_dir/45-vault-eventlog-rotate.sh" "$work/hooks/"
chmod 0755 "$work/hooks"/*
printf '#!/bin/sh\nexit 0\n' > "$work/bin/nginx"
cat > "$work/bin/wget" <<'EOF'
#!/bin/sh
echo "  X-Vault-Settings-Apply: $(cat "$WGET_SERVES")" >&2
EOF
chmod 0755 "$work/bin"/*
export WGET_SERVES="$work/serves"

# The "master": its cmdline starts with "nginx: master process"; it counts HUPs.
: > "$work/hups"
cat > "$work/master.sh" <<'MASTER'
trap 'echo hup >> "$HUPS"' HUP
while :; do sleep 0.1; done
MASTER
HUPS="$work/hups" bash -c 'exec -a "nginx: master process" bash "$1"' sh "$work/master.sh" &
master_pid=$!
sleep 0.3
echo "$master_pid" > "$work/nginx.pid"

live_files() {
    for f in $RENDERED; do printf 'old %s\n' "$f" > "$work/etc/$f"; done
}
hups() { wc -l < "$work/hups" | tr -d ' '; }

# run_apply <file content> <pid file> -> prints "rc=<n>"
run_apply() {
    env PATH="$work/bin:$PATH" VS_LIB="$docker_dir/vault-settings-lib.sh" \
        VS_HOOK_DIR="$work/hooks" VS_CONF_DIR="$work/etc" VS_STATUS_FILE="$work/logs/settings-applied.json" \
        VS_PID_FILE="$2" VS_RELOAD_WAIT=2 VS_HEALTH_URL=http://stub/health VS_WATCH_FUNCTIONS_ONLY=1 \
        VS_ENV_CAPTURED=1 VS_BOOT_GEN=1 \
        bash -c 'set -eu; . "$1"; set +e; apply_file "$2"; echo "rc=$?"' sh "$docker_dir/47-vault-settings-watch.sh" "$1" 2>&1
}
status_field() {
    python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(d[sys.argv[2]])' "$work/logs/settings-applied.json" "$1"
}
file5=$(printf '%s\n' "$HEADER" GENERATION=5 VAULT_UPSTREAM_RATE=2m)

# --- 1. rollback ------------------------------------------------------------------
live_files
echo boot > "$WGET_SERVES"
: > "$work/hups"
out=$(run_apply "$file5" "$work/nginx.pid")
same=yes
for f in $RENDERED; do
    [ "$(cat "$work/etc/$f")" = "old $f" ] || same=no
    cmp -s "$work/etc/$f" "$work/etc/.vault-settings-last-good/$f" || same=no
done
if grep -q 'rc=0' <<<"$out" && [ "$(status_field state)" = rejected ] \
   && grep -q 'reload failed: generation 5 was not live after 2s; restored generation 1' <<<"$(status_field reason)" \
   && [ "$(status_field generation)" = 5 ] && [ "$(status_field applied_generation)" = 1 ]; then
    ok "rollback: timeout -> rejected 'reload failed', generation 5 seen, 1 live"
else
    bad "rollback status: $out / $(cat "$work/logs/settings-applied.json" 2>&1)"
fi
if [ "$same" = yes ]; then ok "rollback: every live file is byte-identical to the backup (the old files)"; else bad "rollback: live files differ from the backup"; fi
sleep 0.3
if [ "$(hups)" = 2 ]; then ok "rollback: two reloads (the new config, then the restored one)"; else bad "rollback: $(hups) SIGHUPs, expected 2"; fi

# --- 2. success -------------------------------------------------------------------
live_files
: > "$work/hups"
# The stub serves whatever id the staged generation include carries, i.e. the
# new workers come up with the new config.
cat > "$work/bin/wget" <<EOF
#!/bin/sh
id=\$(sed -n 's/^add_header X-Vault-Settings-Apply "\\(.*\\)" always;\$/\\1/p' "$work/etc/vault-settings-generation.conf")
echo "  X-Vault-Settings-Apply: \$id" >&2
EOF
chmod 0755 "$work/bin/wget"
out=$(run_apply "$file5" "$work/nginx.pid")
sleep 0.3
if grep -q 'rc=0' <<<"$out" && [ "$(status_field state)" = applied ] && [ "$(status_field applied_generation)" = 5 ] \
   && [ "$(cat "$work/etc/vault-upstream-rate.conf")" = "staged rate 2m" ] && [ "$(hups)" = 1 ]; then
    ok "success: applied generation 5, staged files live, one reload"
else
    bad "success: $out / $(cat "$work/logs/settings-applied.json" 2>&1) / hups $(hups)"
fi

# --- 3. transient: no master ---------------------------------------------------------
live_files
: > "$work/hups"
out=$(run_apply "$file5" "$work/no-such.pid")
if grep -q 'rc=2' <<<"$out" && [ "$(cat "$work/etc/nginx.conf")" = "old nginx.conf" ] && [ "$(hups)" = 0 ] \
   && grep -q 'will retry' <<<"$(status_field reason)"; then
    ok "transient (no master): rc=2 so the loop retries, nothing swapped, no reload"
else
    bad "transient: $out / hups $(hups)"
fi

# --- 4. content failure --------------------------------------------------------------
live_files
out=$(run_apply "$(printf '%s\n' "$HEADER" GENERATION=6 VAULT_UPSTREAM_RATE=refuse)" "$work/nginx.pid")
if grep -q 'rc=0' <<<"$out" && [ "$(status_field state)" = rejected ] && [ "$(cat "$work/etc/nginx.conf")" = "old nginx.conf" ] \
   && grep -q '27-vault-upstream-rate.sh: FATAL: stub refusal' <<<"$(status_field reason)"; then
    ok "content failure (render refused): rc=0 (final, no retry), nothing swapped"
else
    bad "content failure: $out"
fi

# --- 5. 45-'s grammar is part of the render (review B1) ------------------------------
live_files
out=$(run_apply "$(printf '%s\n' "$HEADER" GENERATION=7 VAULT_EVENT_LOG_ROTATE_BYTES=1000)" "$work/nginx.pid")
if [ "$(status_field state)" = rejected ] && grep -q '45-vault-eventlog-rotate.sh: FATAL' <<<"$(status_field reason)" \
   && [ "$(cat "$work/etc/nginx.conf")" = "old nginx.conf" ]; then
    ok "rotation size 1000 from the file: rejected by 45- --grammar in the render"
else
    bad "rotation size: $out / $(cat "$work/logs/settings-applied.json")"
fi
out=$(run_apply "$(printf '%s\n' "$HEADER" GENERATION=8 VAULT_PREFILL_MAX_THREADS=65)" "$work/nginx.pid")
if [ "$(status_field state)" = rejected ] && grep -q 'VAULT_PREFILL_MAX_THREADS=.65. is not a whole number 1..64' <<<"$(status_field reason)"; then
    ok "prefill threads 65 from the file: rejected in the render (28- would ignore it)"
else
    bad "prefill threads: $out / $(cat "$work/logs/settings-applied.json")"
fi

# --- 6. watch_loop retries a transient failure, logs it once ---------------------------
live_files
: > "$work/hups"
printf '%s\n' "$file5" > "$work/core-settings.env"
rm -f "$work/late.pid" "$work/logs/settings-applied.json"
env PATH="$work/bin:$PATH" VS_LIB="$docker_dir/vault-settings-lib.sh" \
    VS_HOOK_DIR="$work/hooks" VS_CONF_DIR="$work/etc" VS_STATUS_FILE="$work/logs/settings-applied.json" \
    VS_SETTINGS_FILE="$work/core-settings.env" VS_PID_FILE="$work/late.pid" VS_POLL=1 VS_RELOAD_WAIT=2 \
    VS_HEALTH_URL=http://stub/health VS_WATCH_FUNCTIONS_ONLY=1 VS_ENV_CAPTURED=1 VS_BOOT_GEN=1 \
    bash -c 'set -eu; . "$1"; watch_loop ""' sh "$docker_dir/47-vault-settings-watch.sh" > "$work/loop.log" 2>&1 &
loop_pid=$!
# wait (bounded) for the first warning, then let at least three more ticks pass
for _ in $(seq 1 20); do grep -q 'no running nginx master found' "$work/loop.log" && break; sleep 0.5; done
sleep 3.5
transient_warns=$(grep -c 'no running nginx master found' "$work/loop.log" || true)
echo "$master_pid" > "$work/late.pid"
for _ in 1 2 3 4 5 6 7 8; do
    grep -q 'applied (nginx reloaded' "$work/loop.log" && break
    sleep 1
done
kill "$loop_pid" 2>/dev/null || true
wait "$loop_pid" 2>/dev/null || true
if [ "$transient_warns" = 1 ] && [ "$(grep -c 'no running nginx master found' "$work/loop.log")" = 1 ]; then
    ok "watch loop: a transient failure over several ticks is logged once per streak"
else
    bad "watch loop: transient warning count $transient_warns: $(cat "$work/loop.log")"
fi
if grep -q 'settings generation 5 applied (nginx reloaded' "$work/loop.log" && [ "$(status_field state)" = applied ]; then
    ok "watch loop: the same content is retried on the next tick and applied once the master is back"
else
    bad "watch loop retry: $(cat "$work/loop.log")"
fi

# --- 7. a different failure mid-streak is reported, not swallowed ----------------------
live_files
rm -f "$work/late.pid"
printf '%s\n' "$file5" > "$work/core-settings.env"
: > "$work/loop2.log"
env PATH="$work/bin:$PATH" VS_LIB="$docker_dir/vault-settings-lib.sh" \
    VS_HOOK_DIR="$work/hooks" VS_CONF_DIR="$work/etc" VS_STATUS_FILE="$work/logs/settings-applied.json" \
    VS_SETTINGS_FILE="$work/core-settings.env" VS_PID_FILE="$work/late.pid" VS_POLL=1 VS_RELOAD_WAIT=2 \
    VS_HEALTH_URL=http://stub/health VS_WATCH_FUNCTIONS_ONLY=1 VS_ENV_CAPTURED=1 VS_BOOT_GEN=1 \
    bash -c 'set -eu; . "$1"; watch_loop ""' sh "$docker_dir/47-vault-settings-watch.sh" > "$work/loop2.log" 2>&1 &
loop_pid=$!
for _ in $(seq 1 20); do grep -q 'no running nginx master found' "$work/loop2.log" && break; sleep 0.5; done
# same file, now a content the render refuses: a different reason in the streak
printf '%s\n' "$HEADER" GENERATION=6 VAULT_UPSTREAM_RATE=refuse > "$work/core-settings.env"
for _ in $(seq 1 20); do grep -q 'stub refusal' "$work/loop2.log" && break; sleep 0.5; done
kill "$loop_pid" 2>/dev/null || true
wait "$loop_pid" 2>/dev/null || true
if grep -q 'stub refusal' "$work/loop2.log" && [ "$(status_field state)" = rejected ] \
   && grep -q 'stub refusal' <<<"$(status_field reason)"; then
    ok "watch loop: a different failure mid-streak is logged and written to the status file"
else
    bad "mid-streak failure swallowed: $(cat "$work/loop2.log") / $(cat "$work/logs/settings-applied.json")"
fi

# reject itself: quiet mode silences only an identical reason
out=$(env VS_LIB="$docker_dir/vault-settings-lib.sh" VS_CONF_DIR="$work/etc" VS_STATUS_FILE="$work/logs/settings-applied.json" \
    VS_WATCH_FUNCTIONS_ONLY=1 VS_ENV_CAPTURED=1 VS_BOOT_GEN=1 \
    bash -c 'set -eu; . "$1"; reject 5 "reason A"; VS_QUIET=1; reject 5 "reason A"; reject 5 "reason B"' sh "$docker_dir/47-vault-settings-watch.sh" 2>&1)
if [ "$(grep -c 'reason A' <<<"$out")" = 1 ] && [ "$(grep -c 'reason B' <<<"$out")" = 1 ] && [ "$(status_field reason)" = "reason B" ]; then
    ok "reject: quiet mode swallows an identical repeat but reports a different reason"
else
    bad "reject quiet mode: $out"
fi

echo "test-settings-watch: $pass passed, $fail failed"
[ "$fail" = 0 ]
