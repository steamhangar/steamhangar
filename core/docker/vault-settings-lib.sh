# shellcheck shell=sh
# Variables set here (VS_RENDERED, VS_ERR, ...) are read by the scripts that
# source this library.
# shellcheck disable=SC2034
# SteamHangar vault-core -- the core settings path (D16c), shared functions.
#
# Installed as /opt/vault/vault-settings-lib.sh and SOURCED (never executed)
# by /docker-entrypoint.d/15-vault-settings.envsh (boot) and
# /docker-entrypoint.d/47-vault-settings-watch.sh (runtime apply). Design:
# docs/handover/d16-settings-audit.md sections 4.1-4.4; ADR-0021 note
# 2026-10-15; core/README.md "Settings from vault-api".
#
# The settings file (VS_SETTINGS_FILE, default
# /etc/vault-settings/core-settings.env, written only by vault-api):
#
#     # generated by vault-api -- do not edit
#     GENERATION=42
#     VAULT_UPSTREAM_RATE=800k
#     VAULT_UPSTREAM_RATE_WINDOW=03:00-07:00
#
# It is NEVER sourced (`. file` would execute it). vs_read_file reads it as
# the nginx worker user (the volume is writable by uid 101, so a root read
# through a planted symlink could leak root-only files into a message), with
# a size cap and a timeout (a planted FIFO must not hang the watcher).
# vs_parse accepts exactly: the header line, a GENERATION line, then
# KEY=VALUE lines whose KEY is in VS_KEYS, each at most once, printable
# ASCII values. Anything else rejects the WHOLE file. Values are not judged
# here: vs_render runs every value through the hooks' own grammars
# (26/27/28/40/45), so there is one grammar per key, not two.
#
# Precedence per key (Q1, Q7): an env value that is not blank wins; else the
# file's value; else the shipped default (vs_default). The env values are
# captured ONCE, at boot, by vs_capture_env into VS_ENV_<KEY> -- 15- then
# overwrites <KEY> itself with the effective value for the later hooks, so
# only the VS_ENV_ copy still says what the operator pinned.
#
# POSIX sh (busybox ash in the image, dash/bash in the docker-free tests).

VS_KEYS="VAULT_UPSTREAM_RATE VAULT_UPSTREAM_RATE_WINDOW VAULT_UPSTREAM_EDGE VAULT_UPSTREAM_POOL_HOSTS VAULT_UPSTREAM_MAX_CONNS VAULT_PREFILL_MAX_THREADS VAULT_TLS_CLIENT_MAX_CONNS VAULT_TLS_MAX_CONNS VAULT_RESOLVER VAULT_EVENT_LOG_ROTATE_BYTES"
VS_FILE_HEADER="# generated by vault-api -- do not edit"
VS_SETTINGS_FILE="${VS_SETTINGS_FILE:-/etc/vault-settings/core-settings.env}"
VS_STATUS_FILE="${VS_STATUS_FILE:-/vault/logs/settings-applied.json}"
VS_HOOK_DIR="${VS_HOOK_DIR:-/docker-entrypoint.d}"
VS_CONF_DIR="${VS_CONF_DIR:-/etc/nginx}"
VS_WORKER_USER=nginx
VS_MAX_BYTES=16384
VS_MAX_LINES=64
# The files one render produces; the watcher swaps exactly these.
VS_RENDERED="nginx.conf vault-upstream-rate.conf vault-upstream-pool.conf vault-upstream-cap.conf vault-settings-generation.conf vault-settings.effective"

# The ASCII whitespace set 27's strip() uses.
VS_WS=$(printf ' \t\n\v\f\r\034\035\036\037X')
VS_WS=${VS_WS%X}

# vs_default <KEY>: the shipped default (what compose supplied before rc18,
# audit 3.5). Every key has an explicit one, so the hooks never see a blank
# value inside the container and the status file can name the value.
vs_default() {
    case "$1" in
        VAULT_UPSTREAM_RATE) echo off ;;
        VAULT_UPSTREAM_RATE_WINDOW) echo 03:00-07:00 ;;
        VAULT_UPSTREAM_EDGE) echo dist-fra1.discovery.steamserver.net ;;
        VAULT_UPSTREAM_POOL_HOSTS) echo off ;;
        VAULT_UPSTREAM_MAX_CONNS) echo 16 ;;
        VAULT_PREFILL_MAX_THREADS) echo 8 ;;
        VAULT_TLS_CLIENT_MAX_CONNS) echo 64 ;;
        VAULT_TLS_MAX_CONNS) echo 256 ;;
        VAULT_RESOLVER) echo 1.1.1.1 ;;
        VAULT_EVENT_LOG_ROTATE_BYTES) echo 67108864 ;;
        *) return 1 ;;
    esac
}

# vs_is_key <word>: true iff <word> is EXACTLY one of VS_KEYS. A literal case
# list on the whole word, after a [A-Z0-9_] character check: a key holding
# spaces, '=', '$' or several allowlisted names never matches, so the eval
# lines that use a key to name a variable only ever see one of these ten
# literals (review D16c B2).
vs_is_key() {
    case "$1" in
        ""|*[!A-Z0-9_]*) return 1 ;;
    esac
    case "$1" in
        VAULT_UPSTREAM_RATE|VAULT_UPSTREAM_RATE_WINDOW|VAULT_UPSTREAM_EDGE|\
        VAULT_UPSTREAM_POOL_HOSTS|VAULT_UPSTREAM_MAX_CONNS|VAULT_PREFILL_MAX_THREADS|\
        VAULT_TLS_CLIENT_MAX_CONNS|VAULT_TLS_MAX_CONNS|VAULT_RESOLVER|\
        VAULT_EVENT_LOG_ROTATE_BYTES) return 0 ;;
    esac
    return 1
}

# vs_check_prefill <value>: the prefill thread count vault-core's floor check
# uses, 1..64, digits only, no leading zero (28- silently ignores anything
# else, so the render refuses it instead -- review D16c N1).
vs_check_prefill() {
    case "$1" in
        ""|*[!0-9]*|0*) return 1 ;;
    esac
    [ "${#1}" -le 2 ] && [ "$1" -le 64 ]
}

# vs_blank <value>: true for "" and for ASCII whitespace only ("not set").
vs_blank() {
    case "$1" in
        *[!$VS_WS]*) return 1 ;;
    esac
    return 0
}

# vs_shown <text>: safe to put into a log line or the status file -- only
# [A-Za-z0-9 ./:;()_+=,[]-] ('[' ']' as octal: IPv6 resolver addresses), every
# other byte (quotes, backslashes, control characters, non-ASCII) as '?', at
# most 200 characters.
vs_shown() {
    printf '%s' "$1" | tr -c 'A-Za-z0-9 ./:;()_+=,\133\135-' '?' | cut -c 1-200
}

# vs_capture_env: record the operator's env value of every key (boot only).
vs_capture_env() {
    [ -z "${VS_ENV_CAPTURED:-}" ] || return 0
    for _vk in $VS_KEYS; do
        eval "_vv=\${$_vk-}"
        # shellcheck disable=SC2154 # _vv is set by the eval above
        export "VS_ENV_$_vk=$_vv"
    done
    export VS_ENV_CAPTURED=1
}

# vs_read_file: the file's content on stdout. Returns 1 when there is no
# file, 2 when it cannot be read (not a regular file, too large, timeout).
vs_read_file() {
    _vf=$VS_SETTINGS_FILE
    case "$_vf" in
        /*) : ;;
        *) return 2 ;;
    esac
    case "$_vf" in
        *[!A-Za-z0-9/_.-]*) return 2 ;;
    esac
    [ -e "$_vf" ] || [ -L "$_vf" ] || return 1
    [ -f "$_vf" ] || return 2
    if [ "$(id -u)" = 0 ]; then
        _vc=$(timeout 5 su -s /bin/sh "$VS_WORKER_USER" -c "head -c $((VS_MAX_BYTES + 1)) -- '$_vf'" 2>/dev/null) || return 2
    else
        _vc=$(timeout 5 head -c $((VS_MAX_BYTES + 1)) -- "$_vf" 2>/dev/null) || return 2
    fi
    [ "$(printf '%s' "$_vc" | wc -c)" -le "$VS_MAX_BYTES" ] || return 2
    printf '%s\n' "$_vc"
}

# vs_parse <content>: sets VS_GEN, VS_HAS_<KEY> (1 or empty), VS_F_<KEY>.
# Returns 1 with VS_ERR set when the file is not exactly what vault-api writes.
vs_parse() {
    VS_GEN=""
    VS_ERR=""
    for _vk in $VS_KEYS; do
        eval "VS_HAS_$_vk=; VS_F_$_vk="
    done
    if [ "$(printf '%s\n' "$1" | wc -l)" -gt "$VS_MAX_LINES" ]; then
        VS_ERR="more than $VS_MAX_LINES lines"
        return 1
    fi
    _vn=0
    _vcr=$(printf '\rX')
    _vcr=${_vcr%X}
    while IFS= read -r _vl || [ -n "$_vl" ]; do
        _vn=$((_vn + 1))
        if [ "$_vn" -gt "$VS_MAX_LINES" ]; then
            VS_ERR="more than $VS_MAX_LINES lines"
            return 1
        fi
        case "$_vl" in
            *"$_vcr"*) VS_ERR="line $_vn contains a carriage return"; return 1 ;;
        esac
        if [ "$_vn" -eq 1 ]; then
            if [ "$_vl" != "$VS_FILE_HEADER" ]; then
                VS_ERR="line 1 is not the vault-api header"
                return 1
            fi
            continue
        fi
        case "$_vl" in
            *=*) _vk=${_vl%%=*}; _vv=${_vl#*=} ;;
            *) VS_ERR="line $_vn is not KEY=VALUE"; return 1 ;;
        esac
        if [ "$_vn" -eq 2 ]; then
            if [ "$_vk" != GENERATION ]; then
                VS_ERR="line 2 is not GENERATION=<n>"
                return 1
            fi
            case "$_vv" in
                [1-9]*) : ;;
                *) VS_ERR="GENERATION is not a positive whole number"; return 1 ;;
            esac
            case "$_vv" in
                *[!0-9]*) VS_ERR="GENERATION is not a positive whole number"; return 1 ;;
            esac
            if [ "${#_vv}" -gt 15 ]; then
                VS_ERR="GENERATION has more than 15 digits"
                return 1
            fi
            VS_GEN=$_vv
            continue
        fi
        # The key must be EXACTLY one allowlisted name (vs_is_key: a literal
        # case list, no substring match) before it is used to name a
        # variable below; anything else rejects the whole file.
        if ! vs_is_key "$_vk"; then
            VS_ERR="line $_vn: key '$(vs_shown "$_vk")' is not a core setting"
            return 1
        fi
        eval "_vh=\$VS_HAS_$_vk"
        # shellcheck disable=SC2154 # _vh is set by the eval above
        if [ -n "$_vh" ]; then
            VS_ERR="line $_vn: $_vk is listed twice"
            return 1
        fi
        if [ -n "$(printf '%s' "$_vv" | tr -d ' -~')" ]; then
            VS_ERR="line $_vn: the value of $_vk has a character outside printable ASCII"
            return 1
        fi
        eval "VS_HAS_$_vk=1; VS_F_$_vk=\$_vv"
    done <<VS_EOF
$1
VS_EOF
    if [ -z "$VS_GEN" ]; then
        VS_ERR="no GENERATION line"
        return 1
    fi
    return 0
}

# vs_resolve <use-file: yes|no>: sets VS_V_<KEY> (effective value) and
# VS_S_<KEY> (env | file | default) for every key.
vs_resolve() {
    for _vk in $VS_KEYS; do
        eval "_ve=\${VS_ENV_$_vk-}"
        # shellcheck disable=SC2154 # _ve is set by the eval above
        if ! vs_blank "$_ve"; then
            _vv=$_ve
            _vs="env"
        else
            _vv=""
            _vs=""
            if [ "$1" = yes ]; then
                eval "_vh=\$VS_HAS_$_vk; _vf=\$VS_F_$_vk"
                # shellcheck disable=SC2154 # _vh/_vf are set by the eval above
                if [ -n "$_vh" ] && ! vs_blank "$_vf"; then
                    _vv=$_vf
                    _vs="file"
                fi
            fi
            if [ -z "$_vs" ]; then
                _vv=$(vs_default "$_vk")
                _vs=default
            fi
        fi
        eval "VS_V_$_vk=\$_vv; VS_S_$_vk=\$_vs"
    done
}

# vs_export: export the effective values under the keys' own names, for the
# hooks (export only works for the calling shell and its children: the boot
# hook is sourced, the watcher calls this in a subshell per attempt).
vs_export() {
    for _vk in $VS_KEYS; do
        eval "export $_vk=\"\$VS_V_$_vk\""
    done
}

# vs_effective_lines: KEY=VALUE<TAB>SOURCE per key (vault-settings.effective,
# read back by 45- for the rotation size and by the watcher for the status).
vs_effective_lines() {
    for _vk in $VS_KEYS; do
        eval "printf '%s=%s\t%s\n' \"\$_vk\" \"\$VS_V_$_vk\" \"\$VS_S_$_vk\""
    done
}

# vs_render <dir> <generation> [apply id]: the boot chain 20 -> 25 -> 26 -> 27 -> 28 into
# <dir>, plus the generation include and the effective-values file, then
# 40's value checks against <dir>. Hook output goes to <dir>/.render.log.
# Returns 1 with VS_ERR set (the first FATAL line) on any failure. Uses the
# exported key values (vs_export first).
vs_render() {
    _vd=$1
    _vg=$2
    _vapply=${3:-boot}
    _vlog="$_vd/.render.log"
    : > "$_vlog"
    VS_ERR=""
    if ! NGINX_ENVSUBST_OUTPUT_DIR="$_vd" "$VS_HOOK_DIR/20-envsubst-on-templates.sh" >> "$_vlog" 2>&1 3>&1; then
        vs_render_fail "the envsubst render failed"
        return 1
    fi
    # The stock hook soft-fails (LEARNINGS WP 5.1): prove it rendered OURS.
    if [ ! -f "$_vd/nginx.conf" ] || ! grep -q 'log_format vault_event' "$_vd/nginx.conf"; then
        vs_render_fail "envsubst did not render the SteamHangar nginx.conf"
        return 1
    fi
    for _vhook in "25-vault-eventlog.sh:$_vd/nginx.conf" \
                  "26-vault-tls-passthrough.sh:$_vd/nginx.conf" \
                  "31-vault-debug-throughput.sh:$_vd/nginx.conf" \
                  "27-vault-upstream-rate.sh:$_vd/vault-upstream-rate.conf" \
                  "28-vault-upstream-pool.sh:$_vd/vault-upstream-pool.conf"; do
        if ! sh "$VS_HOOK_DIR/${_vhook%%:*}" "${_vhook#*:}" >> "$_vlog" 2>&1; then
            vs_render_fail "${_vhook%%:*} refused the values"
            return 1
        fi
    done
    # 45- only runs at boot (its loop re-reads the size), so its grammar is
    # checked here; a value it would refuse must never be "applied" (review
    # D16c B1). Same for the prefill thread count 28- ignores when invalid.
    if ! sh "$VS_HOOK_DIR/45-vault-eventlog-rotate.sh" --grammar >> "$_vlog" 2>&1; then
        vs_render_fail "45-vault-eventlog-rotate.sh refused the values"
        return 1
    fi
    if ! vs_check_prefill "${VAULT_PREFILL_MAX_THREADS:-}"; then
        echo "vault-settings-lib.sh: FATAL: VAULT_PREFILL_MAX_THREADS='$(vs_shown "${VAULT_PREFILL_MAX_THREADS:-}")' is not a whole number 1..64" >> "$_vlog"
        vs_render_fail "the prefill thread count is invalid"
        return 1
    fi
    vs_write_generation_conf "$_vd/vault-settings-generation.conf" "$_vg" "$_vapply" || { vs_render_fail "could not write the generation include"; return 1; }
    vs_effective_lines > "$_vd/vault-settings.effective" || { vs_render_fail "could not write vault-settings.effective"; return 1; }
    if ! sh "$VS_HOOK_DIR/40-vault-preflight.sh" --values "$_vd" >> "$_vlog" 2>&1; then
        vs_render_fail "40-vault-preflight.sh's value checks failed"
        return 1
    fi
    return 0
}

# vs_render_fail <summary>: VS_ERR = summary plus the first FATAL line.
vs_render_fail() {
    _vfatal=$(grep -m 1 'FATAL' "$_vlog" 2>/dev/null | cut -c 1-300 || true)
    VS_ERR="$1${_vfatal:+: $_vfatal}"
}

# vs_write_generation_conf <file> <generation> [apply id]: the /health
# headers that let the watcher see which config the running workers serve.
# The generation is what vault-api compares; the apply id (default "boot",
# else unique per apply attempt) makes the post-reload check exact even when
# a generation repeats -- vault-api restarts at 1 when the settings volume is
# lost, so "same generation" is not "same config".
vs_write_generation_conf() {
    case "$2" in
        ''|*[!0-9]*) return 1 ;;
    esac
    _vid=${3:-boot}
    case "$_vid" in
        ''|*[!A-Za-z0-9.-]*) return 1 ;;
    esac
    {
        echo "# Rendered by vault-core (D16c) -- do not edit. Included in location = /health;"
        echo "# the settings watcher polls it after a reload (core/README.md \"Settings from vault-api\")."
        echo "add_header X-Vault-Settings-Generation \"$2\" always;"
        echo "add_header X-Vault-Settings-Apply \"$_vid\" always;"
    } > "$1"
}

# vault_root_only_dir <dir>: true iff <dir> is a real directory (not a
# symlink), owned by uid 0 and writable by neither group nor others.
# Byte-identical copies live in 21-, 25- and 29- (pinned by
# core/tests/test-root-only-dir.sh).
vault_root_only_dir() {
    [ -d "$1" ] && [ ! -L "$1" ] || return 1
    _vrod=$(stat -c '%u %a' "$1") || return 1
    [ "${_vrod%% *}" = "0" ] || return 1
    [ $(( 0${_vrod#* } & 022 )) -eq 0 ] || return 1
    return 0
}

# vs_json <text>: a JSON string literal of vs_shown's safe subset (no quote,
# backslash or control character can survive vs_shown).
vs_json() {
    printf '"%s"' "$(vs_shown "$1")"
}

# vs_write_status <state> <generation> <applied generation> <reason> <effective file>
# Writes VS_STATUS_FILE atomically for vault-api (GET /v1/settings). As
# root only into a root-only directory chain (SEC-FIX-5, same rule as 29-).
# Never fails the caller: returns 1 and the caller logs.
vs_write_status() {
    _vsd=$(dirname -- "$VS_STATUS_FILE")
    if [ "$(id -u)" = 0 ]; then
        _vc=$_vsd
        while :; do
            vault_root_only_dir "$_vc" || return 1
            [ "$_vc" = / ] && break
            _vc=$(dirname -- "$_vc")
        done
    fi
    [ -d "$_vsd" ] && [ ! -L "$_vsd" ] || return 1
    _vtmp=$(mktemp "$_vsd/.settings-applied.XXXXXX") || return 1
    {
        printf '{"component":"vault-core","state":%s,"generation":%s,"applied_generation":%s,"reason":%s,"updated_at":"%s","keys":{' \
            "$(vs_json "$1")" "${2:-0}" "${3:-0}" "$(vs_json "$4")" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        _vfirst=1
        while IFS= read -r _vline; do
            _vk=${_vline%%=*}
            _vrest=${_vline#*=}
            _vval=${_vrest%"	"*}
            _vsrc=${_vrest##*"	"}
            [ "$_vfirst" = 1 ] || printf ','
            _vfirst=0
            printf '"%s":{"value":%s,"source":%s}' "$(vs_shown "$_vk")" "$(vs_json "$_vval")" "$(vs_json "$_vsrc")"
        done < "$5"
        printf '}}\n'
    } > "$_vtmp" && chmod 0644 "$_vtmp" && mv -f "$_vtmp" "$VS_STATUS_FILE" && return 0
    rm -f "$_vtmp"
    return 1
}
